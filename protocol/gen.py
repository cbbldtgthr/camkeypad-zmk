#!/usr/bin/env python3
"""Generate the C header and Java class for the camkeypad protocol from protocol.toml.

Standard library only. Output is deterministic so `protocol-check` can diff it.
"""

import argparse
import pathlib
import sys
import tomllib
import uuid

TYPES = {
    # name: (size in bytes, C type, Java type)
    "u8": (1, "uint8_t", "int"),
    "u16": (2, "uint16_t", "int"),
    "u32": (4, "uint32_t", "long"),
}

# Tables of named u8 values.
ENUMS = ("state", "mode", "phone_battery")

HEADER_NOTE = "GENERATED by camkeypad-zmk/protocol/gen.py from protocol.toml. Do not edit."


def fail(msg):
    sys.exit(f"protocol.toml: {msg}")


def load(path):
    with open(path, "rb") as f:
        spec = tomllib.load(f)

    if not isinstance(spec.get("version"), int) or not 0 < spec["version"] < 256:
        fail("version must be an integer in 1..255")
    for key in ("service_uuid", "status_char_uuid"):
        try:
            spec[key] = uuid.UUID(spec[key])
        except (KeyError, ValueError):
            fail(f"{key} must be a UUID")
    for enum in ENUMS:
        for name, value in spec[enum].items():
            if not isinstance(value, int) or not 0 <= value < 256:
                fail(f"{enum}.{name} must fit in u8")
        if len(set(spec[enum].values())) != len(spec[enum]):
            fail(f"{enum} values must be unique")
    for name, value in spec["timing"].items():
        if not isinstance(value, int) or value <= 0:
            fail(f"timing.{name} must be a positive integer")

    fields = spec["status"]["fields"]
    if not fields or fields[0] != {"name": "version", "type": "u8"}:
        fail("the first status field must be { name = \"version\", type = \"u8\" }")
    offset = 0
    for field in fields:
        if field.get("type") not in TYPES:
            fail(f"status field {field.get('name')!r} has unknown type {field.get('type')!r}")
        field["offset"] = offset
        offset += TYPES[field["type"]][0]
    spec["status"]["length"] = offset
    return spec


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(part.capitalize() for part in rest)


def uuid_le_bytes(u):
    return ", ".join(f"0x{b:02x}" for b in reversed(u.bytes))


def uuid_zephyr_encode(u):
    g = str(u).split("-")
    return f"BT_UUID_128_ENCODE(0x{g[0]}, 0x{g[1]}, 0x{g[2]}, 0x{g[3]}, 0x{g[4]})"


def gen_c(spec):
    status = spec["status"]
    out = [
        f"/* {HEADER_NOTE} */",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"#define CAMKEYPAD_PROTOCOL_VERSION {spec['version']}",
        "",
    ]
    for key in ("service_uuid", "status_char_uuid"):
        u = spec[key]
        name = "CAMKEYPAD_" + key.upper()
        out += [
            f'#define {name}_STR "{u}"',
            f"/* For Zephyr: BT_UUID_DECLARE_128({name}_ENCODE) */",
            f"#define {name}_ENCODE {uuid_zephyr_encode(u)}",
            "/* Little-endian bytes, e.g. for Adafruit Bluefruit BLEUuid */",
            f"#define {name}_LE {{ {uuid_le_bytes(u)} }}",
            "",
        ]
    for enum in ENUMS:
        out.append(f"enum camkeypad_{enum} {{")
        for name, value in spec[enum].items():
            out.append(f"    CAMKEYPAD_{enum.upper()}_{name.upper()} = {value},")
        out += ["};", ""]
    for name, value in spec["timing"].items():
        out.append(f"#define CAMKEYPAD_{name.upper()} {value}")
    out += ["", f"#define CAMKEYPAD_STATUS_LEN {status['length']}", "", "struct camkeypad_status {"]
    for field in status["fields"]:
        out.append(f"    {TYPES[field['type']][1]} {field['name']};")
    out += [
        "};",
        "",
        "/* Decode a status write. Returns 0 on success, -1 if buf is too short.",
        " * Checking the version is the caller's job. Extra trailing bytes are ignored. */",
        "static inline int camkeypad_status_decode(const uint8_t *buf, size_t len,",
        "                                          struct camkeypad_status *out)",
        "{",
        "    if (len < CAMKEYPAD_STATUS_LEN) {",
        "        return -1;",
        "    }",
    ]
    for field in status["fields"]:
        size, ctype, _ = TYPES[field["type"]]
        parts = [f"(({ctype})buf[{field['offset'] + i}] << {8 * i})" for i in range(size)]
        out.append(f"    out->{field['name']} = {' | '.join(parts)};")
    out += ["    return 0;", "}", ""]
    return "\n".join(out)


def gen_java(spec, package):
    status = spec["status"]
    args = [f for f in status["fields"] if f["name"] != "version"]
    out = [
        f"// {HEADER_NOTE}",
        f"package {package};",
        "",
        "import java.util.UUID;",
        "",
        "public final class CamKeypadProtocol {",
        "    private CamKeypadProtocol() {",
        "    }",
        "",
        f"    public static final int VERSION = {spec['version']};",
        "",
    ]
    for key in ("service_uuid", "status_char_uuid"):
        out.append(f'    public static final UUID {key.upper()} = UUID.fromString("{spec[key]}");')
    out.append("")
    for enum in ENUMS:
        for name, value in spec[enum].items():
            out.append(f"    public static final int {enum.upper()}_{name.upper()} = {value};")
        out.append("")
    for name, value in spec["timing"].items():
        out.append(f"    public static final long {name.upper()} = {value};")
    out += [
        "",
        f"    public static final int STATUS_LEN = {status['length']};",
        "",
        "    /** Encode a status write, little-endian. VERSION is filled in. */",
        "    public static byte[] encodeStatus("
        + ", ".join(f"{TYPES[f['type']][2]} {camel(f['name'])}" for f in args)
        + ") {",
        "        byte[] buf = new byte[STATUS_LEN];",
    ]
    for field in status["fields"]:
        value = "VERSION" if field["name"] == "version" else camel(field["name"])
        for i in range(TYPES[field["type"]][0]):
            shift = f" >>> {8 * i}" if i else ""
            out.append(f"        buf[{field['offset'] + i}] = (byte) (({value}{shift}) & 0xff);")
    out += ["        return buf;", "    }", "}", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--in", dest="src", required=True, type=pathlib.Path)
    parser.add_argument("--out-dir", required=True, type=pathlib.Path)
    parser.add_argument("--java-package", required=True)
    args = parser.parse_args()

    spec = load(args.src)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "camkeypad_protocol.h").write_text(gen_c(spec))
    (args.out_dir / "CamKeypadProtocol.java").write_text(gen_java(spec, args.java_package))


if __name__ == "__main__":
    main()
